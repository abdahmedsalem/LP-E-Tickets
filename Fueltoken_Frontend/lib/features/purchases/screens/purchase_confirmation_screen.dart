class _PurchaseLineRow extends StatelessWidget {
  const _PurchaseLineRow({required this.line});
  final PurchaseConfirmationLine line;

  String _carnetTypeLabel() {
    if (line.carnetType.size > 0 && line.carnetType.faceValue > 0) {
      return Formatters.carnetTypeLabel(
        line.carnetType.size,
        line.carnetType.faceValue,
      );
    }
    return Formatters.normalizeCarnetTypeLabel(
      line.carnetType.name,
      fallbackSize: line.carnetType.size,
      fallbackFaceValue: line.carnetType.faceValue,
    );
  }

  @override
  Widget build(BuildContext context) {
    return Row(
      children: [
        Expanded(
          flex: 5,
          child: Text(
            _carnetTypeLabel(),
            style: GoogleFonts.inter(
              fontSize: 14,
              fontWeight: FontWeight.w700,
              color: AppColors.ink,
              height: 1.2,
            ),
          ),
        ),
        Expanded(
          flex: 4,
          child: Text(
            '${Formatters.numberFr(line.qty)} carnets',
            textAlign: TextAlign.center,
            style: GoogleFonts.inter(
              fontSize: 13,
              fontWeight: FontWeight.w600,
              color: AppColors.muted,
            ),
          ),
        ),
        Expanded(
          flex: 4,
          child: Text(
            Formatters.money(line.totalAmount),
            textAlign: TextAlign.right,
            style: GoogleFonts.inter(
              fontSize: 14,
              fontWeight: FontWeight.w800,
              color: const Color(0xFF2B8F3A),
            ),
          ),
        ),
      ],
    );
  }
}

class _PaymentProofCard extends StatelessWidget {
  const _PaymentProofCard({required this.proofPath, this.proofBytes});

  final String proofPath;
  final Uint8List? proofBytes;

  @override
  Widget build(BuildContext context) {
    final proofFile = File(proofPath);

    return Container(
      width: double.infinity,
      padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 12),
      decoration: BoxDecoration(
        color: const Color(0xFFF8FAFC),
        borderRadius: BorderRadius.circular(20),
        border: Border.all(color: const Color(0xFFE5E7EB)),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Text(
            'Preuve de paiement',
            style: GoogleFonts.inter(
              fontSize: 14,
              fontWeight: FontWeight.w800,
              color: AppColors.ink,
            ),
          ),
          const SizedBox(height: 10),
          ClipRRect(
            borderRadius: BorderRadius.circular(16),
            child: SizedBox(
              height: 84,
              width: double.infinity,
              child: Container(
                color: const Color(0xFFEFF2F5),
                child: proofBytes != null
                    ? Image.memory(
                        proofBytes!,
                        fit: BoxFit.cover,
                        errorBuilder: (_, _, _) => const Center(
                          child: Icon(
                            Icons.broken_image_outlined,
                            color: AppColors.muted,
                            size: 30,
                          ),
                        ),
                      )
                    : Image.file(
                        proofFile,
                        fit: BoxFit.cover,
                        errorBuilder: (_, _, _) => const Center(
                          child: Icon(
                            Icons.broken_image_outlined,
                            color: AppColors.muted,
                            size: 30,
                          ),
                        ),
                      ),
              ),
            ),
          ),
        ],
      ),
    );
  }
}

